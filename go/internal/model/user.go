package model

import (
	"fmt"
	"time"
)

// Userは認証がぶら下がる正準な身元で、このインスタンス上のアカウント1つに
// つき1つ存在する。身元レベルの属性を持つ。すなわちemail (連絡先も兼ねる)、
// インスタンス内で一意なatname (ユーザーが何者かを示す @ハンドル)、そしてリクエストの
// 外でメッセージを描画するときに使うアカウントレベルのlocale / time zone
// (例: ジョブが非同期に描画するパスワードリセットメール) である。
//
// 1インスタンスはちょうど1つのコミュニティを運営する (ADR 0006) ため、身元を
// インスタンスより下の単位に閉じ込める器が無く、atnameの一意性はインスタンスの境界で
// 閉じる (ADR 0007)。表示名は意図的にまだモデル化しておらず、必要が生じるまではatnameを
// ユーザーの表示名としても用いる。パスワードダイジェストは別の資格情報テーブルに保持する
// ため、ここには無い。
type User struct {
	ID       UserID
	Email    string
	Atname   string
	Locale   Locale
	TimeZone string

	// DeletedAtは退会済みアカウントを表す。nilはアカウントがアクティブであること、
	// 非nilはユーザーが退会した時刻を意味する。退会はこの値をセットして (email / atnameの
	// 匿名化と同時に) 行を論理削除し、アカウントを即座に無効化する。物理削除は後続のパージ
	// ジョブに委ねる。認証系のルックアップはこの値が非nilの行を除外するため、退会済み
	// ユーザーがセッションとして再び解決されることはない。
	DeletedAt *time.Time

	// SuspendedAtは管理者が止めたアカウントを表します。nilはアカウントが行動できる
	// こと、非nilは停止された時刻を意味します。DeletedAtと別に持つのは、2つがアカウントを
	// 別の場所に置くためです。停止されたアカウントは身元を保ち (emailもatnameもそのまま
	// です)、止まるのは活動だけですが、退会したアカウントは匿名化されパージへ向かいます。
	SuspendedAt *time.Time

	CreatedAt time.Time
	UpdatedAt time.Time
}

// AnonymizedEmailは退会済みアカウントのemailを上書きする代替emailを導出します。
// ユーザーidを埋め込むことで値をアカウントごとに別のものにし、元のアドレスを再登録用に
// 解放します。
//
// 値を到達不能にしているのは予約TLDの .invalid (RFC 2606) です。サインアップもメール
// アドレス変更も、アドレスへ配送された確認コードを要求しますが、.invalidはそれを受け取れ
// ません。そのためこの値を保持できるアカウントは存在せず、上書きが実在の行との間で
// users.emailのUNIQUE制約に負けることがありません。
func AnonymizedEmail(userID UserID) string {
	return fmt.Sprintf("deleted-%s@deleted.invalid", userID.String())
}

// AnonymizedAtnameは退会済みアカウントのatnameを上書きする代替atnameを導出
// します。ユーザーidを埋め込むことで値をアカウントごとに別のものにし、元のatnameを
// 再利用向けに解放します。
//
// 値を到達不能にしているのはハイフンです。ハイフンはatnameの文字集合であるASCII
// 英数字 / アンダースコアの外にあるため、この値を保持できるアカウントは存在せず、上書きが
// 実在の行との間でusers.atnameのUNIQUE制約に負けることがありません。区切りを文字集合
// 内の文字にするとこれは成り立ちません。10進表記のidは短く、アカウントフォームを通る
// 墓標値を綴れてしまうため、退会に必要な値を先取りされうるからです。users.atnameは長さ
// 上限も形式チェックも無いNOCASE照合のTEXTのため、カラム自体はハイフンを受け付けます。
// この墓標値は再検証もハンドルとしての表示もされません。
func AnonymizedAtname(userID UserID) string {
	return "deleted-" + userID.String()
}

// AdminUsersPerPageは、管理画面の利用者一覧の1ページが持つアカウントの数です。
// リクエストのパラメータではなく定数であるのは、ページの大きさがリクエストの求めうる
// 仕事の量を抑えるものであり、呼び出し側が選べる大きさは、呼び出し側がコミュニティ全体を
// 選べる大きさでもあるためです。
//
// ここに置くのは、ページを埋める読み取りと、その下に描かれるページ番号と、次のページが
// あるかどうかの判断が、同じ単位で数えるようにするためです。
const AdminUsersPerPage = 50
